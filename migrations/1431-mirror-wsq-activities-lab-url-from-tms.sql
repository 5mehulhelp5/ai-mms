-- 1431: Mirror the WSQ Activities/Labs URL (lab_url) from AI-LMS-TMS.
--
-- Fills the Activities/Labs URL on the Courseware card of every WSQ (TGS-)
-- course, which was blank on ALL of them. AI-LMS-TMS
-- (lms-tms.tertiaryinfotech.com) is the source of truth; the storefront mirrors
-- it. Data pulled live 2026-09-19 over HTTPS from
-- GET /api/external/courses?fields=course_code,activities_url (301 TGS- courses
-- carry a value). This migration replays that pull so a rebuilt DB keeps it.
--
-- WHY THIS IS SEPARATE FROM 1411:
--   1411 mirrored the other six courseware links and noted "lab_url is NOT
--   touched -- no TMS counterpart". That was wrong in one respect: the TMS DOES
--   store it (public.course.activities_url, shown as "Activities/Lab" in the LMS
--   Courseware card). It was simply missing from the external API's FIELD_MAP
--   allow-list, which drops unknown fields SILENTLY (200 OK, column absent), so
--   every request for it came back clean-but-empty. Exposed in AI-LMS-TMS
--   commit ec92c55.
--
-- Safety / partner notes:
--   * Products resolved by SKU, never a hardcoded product_id (ids drift between
--     local and prod).
--   * WSQ is SG-only. Every statement joins through a TGS- SKU, so on the MY/GH
--     partner servers (no TGS- products) this is a silent no-op.
--   * Only lab_url is written -- no other courseware column is read or changed.
--   * An existing non-blank lab_url is NEVER clobbered (the ON DUPLICATE guard
--     only fills a blank), so an intentional storefront value always wins over
--     the mirror. Re-running is a no-op.
--   * Rows inserted for a product that had no courseware row default every other
--     column to '' per the table DDL -- safe.
--   * All values are ASCII https:// Google Drive URLs, max 84 chars (verified at
--     generation) -- no apply.php 1366 risk, no 1000-char overflow.
--   * MySQL 5.7 target: literals only, no 8.0-only functions.
--
-- Reported, never guessed:
--   * 6 TGS- courses have a BLANK activities_url in the TMS itself -- listed at
--     the end of this file. Fill them at the SOURCE (the LMS), not here.
--   * 20 TGS- codes in the TMS have no product in the SG catalog (retired
--     courses). They simply do not join and are skipped.

